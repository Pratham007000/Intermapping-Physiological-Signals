# Basic statistical analysis
stats = describe(ecg_data)
ecg_mean = stats.mean
ecg_std = stats.variance ** 0.5
ecg_min = stats.minmax[0]
ecg_max = stats.minmax[1]

# Normalize ECG data
ecg_normalized = (ecg_data - ecg_mean) / ecg_std

# Detect R-peaks
fs = 125  # Assumed sampling rate (Hz)
peaks, _ = find_peaks(ecg_normalized, height=1.5, distance=int(fs * 0.4))  # Min 400ms between peaks

# Generate synthetic PPG
delay_samples = int(0.2 * fs)  # 200 ms delay
b, a = butter(4, 2/(fs/2), btype='low')  # Low-pass filter at 2 Hz
ppg_simulated = filtfilt(b, a, ecg_normalized)  # Smooth ECG
ppg_simulated = np.roll(ppg_simulated, delay_samples)  # Apply delay
ppg_simulated = ppg_simulated / np.max(np.abs(ppg_simulated))  # Normalize

# Calculate heart rate
duration_seconds = len(ecg_data) / fs
heart_rate = (len(peaks) / duration_seconds) * 60  # BPM

# Create visualization
plt.figure(figsize=(15, 8))
plt.subplot(2, 1, 1)
plt.plot(ecg_normalized[:1000], label="Normalized ECG", color='blue', linewidth=1.5)
plt.plot(peaks[peaks < 1000], ecg_normalized[peaks[peaks < 1000]], 'ro', label="R-peaks")
plt.title(f"ECG Signal (Mean: {ecg_mean:.2f}, Std: {ecg_std:.2f}, Heart Rate: {heart_rate:.2f} BPM)")
plt.xlabel("Sample Index")
plt.ylabel("Normalized Amplitude")
plt.legend()
plt.grid(True, alpha=0.3)

plt.subplot(2, 1, 2)
plt.plot(ppg_simulated[:1000], label="Synthetic PPG", color='green', linewidth=1.5)
plt.title("Simulated PPG Signal")
plt.xlabel("Sample Index")
plt.ylabel("Normalized Amplitude")
plt.legend()
plt.grid(True, alpha=0.3)

plt.tight_layout()

# Convert plot to base64
buf = io.BytesIO()
plt.savefig(buf, format='png', dpi=300, bbox_inches='tight')
buf.seek(0)
img_str = base64.b64encode(buf.getvalue()).decode('utf-8')
plt.close()

